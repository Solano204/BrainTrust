    private String callGeminiAPI(String prompt) {
        try {
            String url = String.format(
                    "https://generativelanguage.googleapis.com/v1beta/models/%s:generateContent?key=%s",
                    detectionModel, apiKey
            );

            Map<String, Object> requestBody = new HashMap<>();
            Map<String, Object> content = new HashMap<>();
            content.put("parts", List.of(Map.of("text", prompt)));
            requestBody.put("contents", List.of(content));

            // Add generation config for consistent results
            Map<String, Object> generationConfig = new HashMap<>();
            generationConfig.put("temperature", 0.2); // Low temperature for consistent analysis
            generationConfig.put("maxOutputTokens", 3000);
            generationConfig.put("topP", 0.8);
            generationConfig.put("topK", 40);
            requestBody.put("generationConfig", generationConfig);

            // Set safety settings to be more permissive
            List<Map<String, Object>> safetySettings = Arrays.asList(
                    Map.of("category", "HARM_CATEGORY_HARASSMENT", "threshold", "BLOCK_NONE"),
                    Map.of("category", "HARM_CATEGORY_HATE_SPEECH", "threshold", "BLOCK_NONE"),
                    Map.of("category", "HARM_CATEGORY_SEXUALLY_EXPLICIT", "threshold", "BLOCK_NONE"),
                    Map.of("category", "HARM_CATEGORY_DANGEROUS_CONTENT", "threshold", "BLOCK_NONE")
            );
            requestBody.put("safetySettings", safetySettings);

            // Set headers
            HttpHeaders headers = new HttpHeaders();
            headers.setContentType(MediaType.APPLICATION_JSON);

            HttpEntity<Map<String, Object>> entity = new HttpEntity<>(requestBody, headers);

            log.debug("Calling Gemini API with model: {}", detectionModel);
            ResponseEntity<Map> response = restTemplate.postForEntity(url, entity, Map.class);

            String extractedText = extractTextFromResponse(response.getBody());

            log.debug("Gemini API response received: {} characters", extractedText.length());
            return extractedText;

        } catch (Exception e) {
            log.error("❌ Gemini API call failed", e);
            throw new RuntimeException("Gemini API call failed: " + e.getMessage());
        }
    }

    @SuppressWarnings("unchecked")
    private String extractTextFromResponse(Map<String, Object> response) {
        try {
            List<Map<String, Object>> candidates =
                    (List<Map<String, Object>>) response.get("candidates");

            if (candidates == null || candidates.isEmpty()) {
                log.warn("No candidates in Gemini response");
                return "{}";
            }

            Map<String, Object> firstCandidate = candidates.get(0);
            Map<String, Object> content =
                    (Map<String, Object>) firstCandidate.get("content");

            if (content == null) {
                log.warn("No content in Gemini candidate");
                return "{}";
            }

            List<Map<String, Object>> parts =
                    (List<Map<String, Object>>) content.get("parts");

            if (parts == null || parts.isEmpty()) {
                log.warn("No parts in Gemini content");
                return "{}";
            }

            String text = (String) parts.get(0).get("text");
            return text != null ? text.trim() : "{}";

        } catch (Exception e) {
            log.error("❌ Error parsing Gemini response", e);
            return "{}";
        }
    }

    private BigDecimal parseAIProbabilityFromResponse(String response) {
        try {
            String cleanResponse = cleanJsonResponse(response);
            Map<String, Object> jsonResponse = objectMapper.readValue(cleanResponse, Map.class);

            if (jsonResponse.containsKey("ai_probability")) {
                Object prob = jsonResponse.get("ai_probability");
                if (prob instanceof Number) {
                    double probability = ((Number) prob).doubleValue();
                    probability = Math.max(0.0, Math.min(1.0, probability));
                    return new BigDecimal(probability).setScale(4, RoundingMode.HALF_UP);
                } else if (prob instanceof String) {
                    double probability = Double.parseDouble((String) prob);
                    probability = Math.max(0.0, Math.min(1.0, probability));
                    return new BigDecimal(probability).setScale(4, RoundingMode.HALF_UP);
                }
            }

            log.warn("No ai_probability found in response, using fallback");
            return new BigDecimal("0.5");

        } catch (Exception e) {
            log.warn("Could not parse probability from JSON response: {}", e.getMessage());
            return extractProbabilityFromText(response);
        }
    }

    private String cleanJsonResponse(String response) {
        String cleaned = response.trim();

        // Remove markdown code blocks
        if (cleaned.startsWith("```json")) {
            cleaned = cleaned.substring(7);
        } else if (cleaned.startsWith("```")) {
            cleaned = cleaned.substring(3);
        }

        if (cleaned.endsWith("```")) {
            cleaned = cleaned.substring(0, cleaned.length() - 3);
        }

        return cleaned.trim();
    }

    private BigDecimal extractProbabilityFromText(String text) {
        try {
            Pattern pattern = Pattern.compile("0\\.\\d+|\\d+\\.\\d+|\\d+%");
            Matcher matcher = pattern.matcher(text.toLowerCase());

            while (matcher.find()) {
                String match = matcher.group();

                if (match.contains("%")) {
                    String numberStr = match.replaceAll("[^0-9.]", "");
                    if (!numberStr.isEmpty()) {
                        double percent = Double.parseDouble(numberStr);
                        double probability = percent / 100.0;
                        probability = Math.max(0.0, Math.min(1.0, probability));
                        return new BigDecimal(probability).setScale(4, RoundingMode.HALF_UP);
                    }
                } else if (match.matches(".*[0-9]+\\.[0-9]+.*")) {
                    String numberStr = match.replaceAll("[^0-9.]", "");
                    if (!numberStr.isEmpty()) {
                        double probability = Double.parseDouble(numberStr);
                        if (probability <= 1.0) {
                            probability = Math.max(0.0, Math.min(1.0, probability));
                            return new BigDecimal(probability).setScale(4, RoundingMode.HALF_UP);
                        }
                    }
                }
            }
        } catch (Exception e) {
            log.warn("Error extracting probability from text: {}", e.getMessage());
        }

        return new BigDecimal("0.5").setScale(4, RoundingMode.HALF_UP);
    }

    private List<DetectedSegment> generateSegmentsFromAnalysis(String content, String response, BigDecimal overallProbability) {
        List<DetectedSegment> segments = new ArrayList<>();

        try {
            String cleanResponse = cleanJsonResponse(response);
            Map<String, Object> jsonResponse = objectMapper.readValue(cleanResponse, Map.class);

            if (jsonResponse.containsKey("segments") && jsonResponse.get("segments") instanceof List) {
                @SuppressWarnings("unchecked")
                List<Map<String, Object>> segmentList = (List<Map<String, Object>>) jsonResponse.get("segments");

                log.debug("Found {} potential segments in response", segmentList.size());

                for (Map<String, Object> segmentData : segmentList) {
                    DetectedSegment segment = extractSegment(content, segmentData, overallProbability);
                    if (segment != null) {
                        segments.add(segment);
                        log.debug("✅ Added segment: '{}...' (prob: {})",
                                segment.getText().substring(0, Math.min(30, segment.getText().length())),
                                segment.getAiProbability());
                    }
                }
            }

            // Fallback: If no segments were extracted, create intelligent segments
            if (segments.isEmpty() && overallProbability.compareTo(new BigDecimal("0.6")) > 0) {
                log.info("No segments found in JSON, creating fallback segments");
                segments.addAll(createFallbackSegments(content, overallProbability));
            }

        } catch (Exception e) {
            log.warn("Could not parse segments from response: {}", e.getMessage());
            // Create fallback segments on any error
            if (overallProbability.compareTo(new BigDecimal("0.6")) > 0) {
                segments.addAll(createFallbackSegments(content, overallProbability));
            }
        }

        log.info("Final segment count: {}", segments.size());
        return segments;
    }

    private DetectedSegment extractSegment(String content, Map<String, Object> segmentData, BigDecimal defaultProbability) {
        try {
            String segmentText = (String) segmentData.get("text");

            if (segmentText == null || segmentText.trim().isEmpty()) {
                log.debug("Segment text is null or empty");
                return null;
            }

            segmentText = segmentText.trim();

            // Find exact match in content
            int startIndex = findBestMatch(content, segmentText);

            if (startIndex < 0) {
                log.debug("Segment not found in original text: '{}'",
                        segmentText.substring(0, Math.min(50, segmentText.length())));
                return null;
            }

            int endIndex = startIndex + segmentText.length();

            // Get segment probability
            BigDecimal segmentProbability = extractSegmentProbability(segmentData, defaultProbability);

            // Get reason
            String reason = (String) segmentData.get("reason");
            if (reason == null || reason.trim().isEmpty()) {
                reason = "AI pattern detected";
            }

            return new DetectedSegment(
                    segmentText,
                    startIndex,
                    endIndex,
                    segmentProbability,
                    reason
            );

        } catch (Exception e) {
            log.warn("Error processing segment: {}", e.getMessage());
            return null;
        }
    }

    private int findBestMatch(String content, String segment) {
        // Try exact match first
        int index = content.indexOf(segment);
        if (index >= 0) {
            return index;
        }

        // Try case-insensitive match
        String lowerContent = content.toLowerCase();
        String lowerSegment = segment.toLowerCase();
        index = lowerContent.indexOf(lowerSegment);
        if (index >= 0) {
            return index;
        }

        // Try finding similar text (remove extra whitespace)
        String normalizedContent = content.replaceAll("\\s+", " ");
        String normalizedSegment = segment.replaceAll("\\s+", " ");
        index = normalizedContent.indexOf(normalizedSegment);
        if (index >= 0) {
            // Calculate original position
            return calculateOriginalPosition(content, normalizedContent, index);
        }

        // Try partial match (at least 70% of the segment)
        if (segment.length() > 30) {
            int partialLength = (int) (segment.length() * 0.7);
            String partialSegment = segment.substring(0, partialLength);
            index = content.indexOf(partialSegment);
            if (index >= 0) {
                return index;
            }
        }

        return -1;
    }

    private int calculateOriginalPosition(String original, String normalized, int normalizedIndex) {
        int originalPos = 0;
        int normalizedPos = 0;

        while (normalizedPos < normalizedIndex && originalPos < original.length()) {
            if (!Character.isWhitespace(original.charAt(originalPos))) {
                normalizedPos++;
            }
            originalPos++;
        }

        return originalPos;
    }

    private BigDecimal extractSegmentProbability(Map<String, Object> segmentData, BigDecimal defaultValue) {
        try {
            Object prob = segmentData.get("probability");

            if (prob instanceof Number) {
                double probValue = ((Number) prob).doubleValue();
                probValue = Math.max(0.0, Math.min(1.0, probValue));
                return new BigDecimal(probValue).setScale(4, RoundingMode.HALF_UP);
            } else if (prob instanceof String) {
                double probValue = Double.parseDouble((String) prob);
                probValue = Math.max(0.0, Math.min(1.0, probValue));
                return new BigDecimal(probValue).setScale(4, RoundingMode.HALF_UP);
            }
        } catch (Exception e) {
            log.debug("Could not extract segment probability: {}", e.getMessage());
        }

        // Use default probability (usually the overall probability)
        return defaultValue;
    }

    private List<DetectedSegment> createFallbackSegments(String content, BigDecimal probability) {
        List<DetectedSegment> segments = new ArrayList<>();

        // Split content into sentences
        String[] sentences = content.split("[.!?]+");

        if (sentences.length == 0) {
            return segments;
        }

        // Take up to 3 segments evenly distributed
        int step = Math.max(1, sentences.length / 3);
        int count = 0;
        int currentPos = 0;

        for (int i = 0; i < sentences.length && count < 3; i += step) {
            String sentence = sentences[i].trim();

            if (sentence.length() >= 20) {
                int startIndex = content.indexOf(sentence, currentPos);

                if (startIndex >= 0) {
                    segments.add(new DetectedSegment(
                            sentence,
                            startIndex,
                            startIndex + sentence.length(),
                            probability,
                            "Detected AI writing patterns"
                    ));
                    count++;
                    currentPos = startIndex + sentence.length();
                }
            }
        }

        return segments;
    }

    private Map<String, Object> buildDetectionMetadata(String content, String response, ModelType modelType) {
        Map<String, Object> metadata = new HashMap<>();
        Map<String, Object> detailedMetrics = new HashMap<>();

        try {
            String cleanResponse = cleanJsonResponse(response);
            Map<String, Object> jsonResponse = objectMapper.readValue(cleanResponse, Map.class);

            metadata.put("analysis_summary", jsonResponse.get("analysis_summary"));
            metadata.put("confidence", jsonResponse.get("confidence"));

            if (jsonResponse.containsKey("detection_reasons")) {
                metadata.put("detection_reasons", jsonResponse.get("detection_reasons"));
            }

        } catch (Exception e) {
            log.warn("Could not parse metadata from response: {}", e.getMessage());
        }

        // Add basic content metrics
        metadata.put("detected_language", "en");
        metadata.put("analysis_quality", "HIGH");
        metadata.put("word_count", content.split("\\s+").length);
        metadata.put("character_count", content.length());
        metadata.put("provider", "Google Gemini");
        metadata.put("model_version", detectionModel);
        metadata.put("analysis_timestamp", new Date().toString());

        // Detailed metrics
        detailedMetrics.put("perplexity", "N/A");
        detailedMetrics.put("burstiness", "N/A");
        detailedMetrics.put("confidence_score", "0.85");
        detailedMetrics.put("model_used", modelType.name());

        metadata.put("detailed_metrics", detailedMetrics);

        return metadata;
    }

